			<section class="study-sec">
				<h2><span class="sec-num">17</span> <span data-i18n="study.s17.t">المتطلب السابق</span></h2>
				<ul>
					<li data-i18n="study.s17.p1">هو مقرر يشترط استكماله لدراسة مقرر لاحق وتنطبق عليه الشروط التالية:</li>
					<li data-i18n="study.s17.p2">لا يجوز للطالب أن يدرس مقررًا ما قبل أن يدرس متطلبه السابق.</li>
					<li data-i18n="study.s17.p3">لا يجوز للطالب أن يسجل مقررًا متزامنًا مع متطلبه السابق إلا إذا كان قد درس المتطلب السابق نجاحًا أو رسوبًا، أو كان تخرجه يتوقف على ذلك، وذلك بعد موافقة المرشد الأكاديمي وعميد المعهد.</li>
