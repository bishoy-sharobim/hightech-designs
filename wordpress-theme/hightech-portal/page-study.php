				<h2><span class="sec-num">14</span> <span data-i18n="study.s14.t">إنذار الطالب وفصله من المعهد</span></h2>
				<ul>
					<li data-i18n="study.s14.p1">يتم إنذار كل طالب يحصل على معدل تراكمي أقل من (D) باستثناء الفصل الدراسي الأول من التحاقه بالمعهد.</li>
					<li data-i18n="study.s14.p2">لا يسمح للطالب المنذر أكاديميًّا بالتسجيل في الفصل الدراسي التالي لأكثر من 12 ساعة معتمدة.</li>
					<li data-i18n="study.s14.p3">على الطالب الذي قد وجه له إنذار أكاديمي أن يرفع معدله التراكمي إلى (D) فأكثر لإلغاء مفعول الإنذار الأكاديمي، وذلك في مدة أقصاها فصلان دراسيان من تاريخ الإنذار.</li>
					<li data-i18n="study.s14.p4">يفصل الطالب إذا أخفق في رفع المعدل التراكمي إلى (D) بعد مرور مدة الفصلين الدراسيين.</li>
				</ul>
			</section>
			<section class="study-sec">
				<h2><span class="sec-num">15</span> <span data-i18n="study.s15.t">التسجيل</span></h2>
				<p data-i18n="study.s15.p1">على الطالب أن يقوم بالتسجيل للفصل الدراسي وفقًا للتقويم الدراسي الذي يحدده المعهد، وذلك بناءً على موافقة المرشد الأكاديمي واعتماد عميد المعهد ، ويُعد المعهد التقويم الدراسي السنوي ويعلنه للطلاب على الموقع الإلكتروني للمعهد، ويقوم الطالب بتسجيل المقررات الدراسية التي يختارها من خلال نماذج طلب التسجيل بمعرفة المرشد الأكاديمي قبل بداية كل فصل دراسي.</p>
			</section>
