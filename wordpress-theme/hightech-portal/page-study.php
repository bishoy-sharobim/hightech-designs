			<section class="study-sec">
				<h2><span class="sec-num">18</span> <span data-i18n="study.s18.t">الإضافة والحذف والانسحاب</span></h2>
				<ul>
					<li data-i18n="study.s18.p1">يسمح للطالب بالقيام بإجراءات الحذف والإضافة خلال الفترة المحددة لذلك في الحالات التالية:</li>
					<li data-i18n="study.s18.p2">إذا قام بتغيير تخصصه.</li>
					<li data-i18n="study.s18.p3">إذا كان تخرجه متوقعًا في الفصل الدراسي الذي سجل فيه، وكانت عملية الحذف والإضافة ضرورية لتخرجه.</li>
					<li data-i18n="study.s18.p4">بعد موافقة المرشد الأكاديمي، يمكن للطالب إضافة مقرر أو أكثر خلال الأسبوعين الأول والثاني من بدء الفصل الدراسي مع مراعاة الحد الأقصى للعبء الدراسي الفصلي.</li>
					<li data-i18n="study.s18.p5">يجوز للطالب الانسحاب من مقررات دراسية تم التسجيل فيها خلال أسبوعين على الأكثر من بداية الفصل الدراسي، ويحصل على تقدير (منسحب) وذلك في المقررات التي انسحب منها بحيث لا يقل عدد الساعات المسجلة للطالب عن الحد الأدنى للتسجيل في الفصل الدراسي الواحد، أما إذا انسحب بعد هذه المواعيد فيعتبر راسبا (F) ويتم أخذ ذلك في الاعتبار عند حساب معدل نقاطه التراكمي.</li>
					<li data-i18n="study.s18.p6">الطالب الذي يرغب في الانسحاب من الفصل الدراسي بالكامل لظروف المرض أو بعذر يقبله مجلس إدارة المعهد عليه التقدم لشئون التعليم والطلاب للحصول على موافقة المعهد على الانسحاب ولا تدخل المقررات التي انسحب منها الطالب في حساب المعدل التراكمي ويحصل على تقدير (منسحب) فيها ويقوم بإعادة هذه المقررات وامتحانها في فصل دراسي لاحق بعد دفع رسوم الخدمة التعليمية المقررة.</li>
				</ul>
			</section>
			<section class="study-sec">
				<h2><span class="sec-num">19</span> <span data-i18n="study.s19.t">إعادة دراسة المقررات</span></h2>
