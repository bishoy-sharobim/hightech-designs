			<section class="study-sec">
				<h2><span class="sec-num">13</span> <span data-i18n="study.s13.t">العبء الدراسي</span></h2>
				<ul>
					<li data-i18n="study.s13.p1">العبء الدراسي هو مجموع الساعات المعتمدة التي يسمح للطالب بتسجيلها في الفصل الدراسي الواحد بحيث يكون:</li>
					<li data-i18n="study.s13.p2">الحد الأدنى للساعات المعتمدة التي يدرسها الطالب في كل من الفصلين الدراسيين الأول والثاني هو (13 ساعة معتمدة) ويجوز تخفيضه للطالب بناءً على توصية المرشد الأكاديمي وموافقة عميد المعهد إذا كان لديه عذر مقبول.</li>
					<li data-i18n="study.s13.p3">الحد الأقصى للساعات المعتمدة التي يدرسها الطالب في كل من الفصلين الدراسيين الأول والثاني هو (19 ساعة معتمدة).</li>
					<li data-i18n="study.s13.p4">الحــــد الأقصى للساعات المعتمدة التي يدرسها الطالب في الفصل الدراسي الصيفي لا تزيد عن (6 ساعات معتمدة) بما لا يزيد عن مادتين.</li>
					<li data-i18n="study.s13.p5">يجوز للطالب تسجيل 3 ساعات معتمدة إضافية عن الحد الأقصى فى حدود مادة آخرى إذا كان تخرجه يتوقف على ذلك.</li>
					<li data-i18n="study.s13.p6">يمكن للطالب أن ينهي دراسته في أقل من المدة النمطية، وكذلك يمكن للطالب ذى الظروف الخاصة إنهاء برنامج دراسته في مدة لا تتعدى ضعفي المدة النمطية.</li>
				</ul>
