				<h2><span class="sec-num">16</span> <span data-i18n="study.s16.t">التسجيل المتأخر</span></h2>
				<p data-i18n="study.s16.p1">في حالة تقدم الطلاب للتسجيل بعد بداية الفصل الدراسي يتم عرض حالتهم على لجنة شئون التعليم والطلاب ثم مجلس إدارة المعهد للنظر في سبب تأخرهم ويعتبرون غائبين عن الفترة السابقة ما لم يتقدموا بأعذار يقبلها مجلس إدارة المعهد، ويكونوا مسئولين عن تحصيل المواد العلمية للفترة السابقة، ويوقع على المتأخرين عن التسجيل رسم التسجيل المتأخر الذي يحدده مجلس إدارة المعهد.</p>
